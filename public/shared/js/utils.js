/* 通用工具：DOM、日期、格式化、图标 */

export const $ = (sel, root = document) => root.querySelector(sel);
export const $$ = (sel, root = document) => [...root.querySelectorAll(sel)];

export function esc(s) {
  if (s === null || s === undefined) return '';
  return String(s)
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;').replace(/'/g, '&#39;');
}

export function debounce(fn, wait = 250) {
  let t;
  return (...a) => { clearTimeout(t); t = setTimeout(() => fn(...a), wait); };
}

export function initials(name) {
  const n = String(name || '?').trim();
  if (!n) return '?';
  if (/[一-龥]/.test(n)) return n.slice(-2);
  return n.slice(0, 2).toUpperCase();
}

export function avatarColor(name) {
  const palette = ['#4F46E5', '#F59E0B', '#10B981', '#EC4899', '#0EA5E9', '#8B5CF6', '#EF4444', '#14B8A6'];
  let h = 0;
  for (const ch of String(name || '')) h = (h * 31 + ch.charCodeAt(0)) >>> 0;
  return palette[h % palette.length];
}

/** 2026-09-29 → 09-29 */
export function md(iso) { return iso ? String(iso).slice(5) : '--'; }

/** 2026-09-29 → 9月29日 */
export function cnDate(iso) {
  if (!iso) return '--';
  const [, m, d] = String(iso).split('-');
  return `${Number(m)}月${Number(d)}日`;
}

export function todayStr() {
  const d = new Date();
  const p = (n) => String(n).padStart(2, '0');
  return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())}`;
}

export function weekday(iso) {
  if (!iso) return '';
  return '周' + '日一二三四五六'[new Date(`${iso}T00:00:00`).getDay()];
}

export function daysAgo(iso) {
  if (!iso) return null;
  const a = Date.parse(`${iso}T00:00:00`);
  const b = Date.parse(`${todayStr()}T00:00:00`);
  return Math.round((b - a) / 86400000);
}

export function addDaysStr(iso, n) {
  const d = new Date(`${iso}T00:00:00`);
  d.setDate(d.getDate() + n);
  const p = (x) => String(x).padStart(2, '0');
  return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())}`;
}

export function relativeTime(iso) {
  if (!iso) return '';
  const diff = (Date.now() - new Date(iso).getTime()) / 1000;
  if (diff < 60) return '刚刚';
  if (diff < 3600) return `${Math.floor(diff / 60)} 分钟前`;
  if (diff < 86400) return `${Math.floor(diff / 3600)} 小时前`;
  if (diff < 86400 * 7) return `${Math.floor(diff / 86400)} 天前`;
  return cnDate(String(iso).slice(0, 10));
}

export function num(n, d = 0) {
  if (n === null || n === undefined || n === '') return '--';
  return Number(n).toLocaleString('zh-CN', { minimumFractionDigits: d, maximumFractionDigits: d });
}

export function pct(n) { return `${Math.round(Number(n) || 0)}%`; }

export function parseTags(str) {
  return String(str || '').split(/[,，\s]+/).map((s) => s.trim()).filter(Boolean);
}

/** 表单序列化：读取容器内所有 [data-f] 的值 */
export function readForm(root) {
  const out = {};
  $$('[data-f]', root).forEach((el) => {
    const key = el.dataset.f;
    if (el.type === 'checkbox') out[key] = el.checked;
    else if (el.dataset.type === 'num') out[key] = el.value === '' ? 0 : Number(el.value);
    else if (el.dataset.type === 'tags') out[key] = parseTags(el.value);
    else out[key] = el.value;
  });
  return out;
}

export function setForm(root, values) {
  $$('[data-f]', root).forEach((el) => {
    const key = el.dataset.f;
    const v = values[key];
    if (v === undefined) return;
    if (el.type === 'checkbox') el.checked = !!v;
    else if (el.dataset.type === 'tags') el.value = Array.isArray(v) ? v.join(' ') : v;
    else el.value = v ?? '';
  });
}

